"""Every llama-server option, and llmfit's decision about it.

llmfit emits a fraction of what llama-server accepts. Which of the rest are
deliberate and which are oversights was, until this file existed, knowable only
by someone reading the upstream documentation and noticing. That is how the
first several rounds of gaps were found, and it only finds what somebody happens
to read.

So every option carries a recorded decision. A flag llmfit has never considered
fails a test rather than sitting quietly in the gap between what the engine can
do and what llmfit asks it to. When llama.cpp adds options, which it does
constantly, the test is what notices.

Decisions:

``USED``
    llmfit emits it.
``RUNTIME``
    Concerns how the server is operated rather than how the model is
    configured: TLS, CORS, logging, the web UI. llmfit sets up a model, and
    someone putting a server in front of other people has requirements llmfit
    cannot guess.
``ALIAS``
    A second spelling of a flag already covered.
``DEFAULT``
    The engine's own default is what llmfit would choose, so saying it again
    adds noise to the command line and another thing to keep in step.
``MANUAL``
    A deliberate choice belonging to the person, not the tool: which weights to
    load, a control vector, a LoRA adapter, a grammar for their own schema.
``TODO``
    Considered and worth having, with a note on what it needs.
"""


"""Ollama registration.

Writes a Modelfile carrying the tuned parameters and runs ``ollama create``, so
the model shows up in ``ollama list`` and in every app that talks to Ollama —
with this machine's tuning already applied, rather than Ollama's defaults.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any, Dict, Optional

from llmfit.types import ModelSpec, RuntimeConfig
from llmfit.util import http
from llmfit.util.fs import app_dir, ensure_dir, write_text
from llmfit.util.proc import run, which


def is_installed() -> bool:
    return which("ollama") is not None or http.request(
        "http://127.0.0.1:11434/api/tags", timeout=2
    ).ok


def tag_for(spec: ModelSpec) -> str:
    return f"llmfit-{re.sub(r'[^a-z0-9._-]', '-', spec.id.lower())}"


def register_in_ollama(spec: ModelSpec, config: RuntimeConfig,
                       gguf_path: Optional[Path] = None) -> Dict[str, Any]:
    if not which("ollama"):
        return {"target": "ollama", "ok": False,
                "note": "Ollama is not installed; skipped"}

    tag = tag_for(spec)
    # Prefer deriving from the official tag: Ollama stores only the parameter
    # delta, so tuning costs no extra disk. Only fall back to the raw GGUF (which
    # Ollama copies into its own store) when there is no official tag.
    if spec.ollama_name and not config.extra.get("from_gguf"):
        source, duplicates_disk = spec.ollama_name, False
    elif gguf_path:
        source, duplicates_disk = str(gguf_path), True
    else:
        return {"target": "ollama", "ok": False,
                "note": "no Ollama tag and no local GGUF to import from"}

    modelfile = _modelfile(source, config)
    path = write_text(ensure_dir(app_dir() / "modelfiles") / f"{tag}.Modelfile", modelfile)
    result = run(["ollama", "create", tag, "-f", str(path)], timeout=3600)

    if not result.ok:
        return {"target": "ollama", "ok": False, "modelfile": str(path),
                "note": f"`ollama create` failed: {result.output.strip()[:300]}"}
    note = (f"run it with `ollama run {tag}`"
            + ("; note Ollama copied the weights into its own store, so they "
               "occupy disk twice" if duplicates_disk else
               "; derived from the official tag, so no extra disk is used"))
    if spec.supports_vision and duplicates_disk:
        # A Modelfile FROM a single GGUF carries the language model only. Ollama
        # bundles the projector inside its own official tags, so that route
        # keeps vision; this one does not, and saying so beats a user
        # discovering it by sending an image.
        note += ("; built from the language model alone, so this tag is "
                 "text-only — use the official Ollama tag for vision")
    return {
        "target": "ollama", "ok": True, "name": tag, "modelfile": str(path),
        "note": note,
    }


def _modelfile(source: str, config: RuntimeConfig) -> str:
    lines = [
        "# Generated by llmfit — tuned for this machine and use case.",
        f"FROM {source}",
        "",
        f"PARAMETER num_ctx {config.context_tokens}",
        f"PARAMETER num_gpu {config.gpu_layers}",
        f"PARAMETER num_batch {config.ubatch_size}",
        f"PARAMETER temperature {config.temperature}",
        f"PARAMETER top_p {config.top_p}",
        f"PARAMETER top_k {config.top_k}",
        f"PARAMETER min_p {config.min_p}",
        f"PARAMETER repeat_penalty {config.repeat_penalty}",
    ]
    if config.threads:
        lines.append(f"PARAMETER num_thread {config.threads}")
    for stop in config.extra.get("stop", []):
        lines.append(f'PARAMETER stop "{stop}"')
    return "\n".join(lines) + "\n"

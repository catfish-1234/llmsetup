"""llama-swap configuration.

llama-swap is a proxy that sits in front of local inference servers and swaps
models on demand, so one OpenAI-compatible endpoint can serve many models
without keeping them all resident. That is exactly the shape of a machine where
VRAM only fits one model at a time but the user wants several available.

llmfit already knows each model's tuned command line, which is the hard part of
a llama-swap config — so generating one is close to free and saves the user
hand-writing a launch command per model.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

import yaml

from llmfit.types import ModelSpec, RuntimeConfig
from llmfit.util.fs import app_dir, ensure_dir, write_text
from llmfit.util.proc import which


def is_installed() -> bool:
    return which("llama-swap") is not None


def config_path() -> Path:
    return ensure_dir(app_dir() / "llama-swap") / "config.yaml"


def build_config(
    entries: Sequence[Tuple[ModelSpec, RuntimeConfig, List[str]]],
    ttl_seconds: int = 300,
    listen_port: int = 8080,
) -> Dict[str, Any]:
    """Build a llama-swap config from tuned models.

    ``ttl`` is what makes swapping worth it: an idle model is unloaded so the
    next one has room, which is the whole point on a single-GPU machine.
    """
    models: Dict[str, Any] = {}
    for spec, config, command in entries:
        models[spec.id] = {
            "cmd": " ".join(command),
            "proxy": f"http://127.0.0.1:{config.port}",
            "ttl": ttl_seconds,
            "aliases": [spec.ollama_name] if spec.ollama_name else [],
            "checkEndpoint": "/health",
        }
    return {
        "healthCheckTimeout": 300,
        "logLevel": "info",
        "startPort": listen_port,
        "models": models,
        # Only one model resident at a time: the reason to run llama-swap at all
        # is that they do not all fit together.
        "groups": {
            "default": {
                "swap": True,
                "exclusive": True,
                "members": list(models),
            }
        },
    }


def write_config(entries, ttl_seconds: int = 300,
                 path: Optional[Path] = None) -> Dict[str, Any]:
    target = path or config_path()
    document = build_config(entries, ttl_seconds=ttl_seconds)
    header = (
        "# Generated by llmfit. Each model carries the launch command llmfit\n"
        "# tuned for this machine. Start with:  llama-swap --config <this file>\n"
        "# Models are exclusive: one is resident at a time and idle ones unload\n"
        "# after their ttl, which is what makes swapping possible on one GPU.\n\n"
    )
    write_text(target, header + yaml.safe_dump(document, sort_keys=False))
    return {
        "target": "llama_swap", "ok": True, "path": str(target),
        "models": list(document["models"]),
        "note": (f"run `llama-swap --config {target}` for one endpoint that "
                 f"serves {len(document['models'])} model(s) on demand"),
    }

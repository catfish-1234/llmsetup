"""Ollama adapter.

Two provisioning paths, and the choice between them matters for disk:

* the model has an ``ollama_name``, pull the official tag, then create a thin
  derived model (``FROM <base>``) carrying our tuned PARAMETERs. Ollama stores
  only the parameter delta, so tuning costs no extra gigabytes.
* it does not. Download the GGUF into the shared store and ``ollama create``
  from that path. This copies the weights into Ollama's blob store, which we
  warn about rather than doing silently.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from llmsetup.runtimes.base import Endpoint, Runtime, RuntimeUnavailable
from llmsetup.runtimes.gguf_store import CachedModelUnavailable, fetch_gguf, require_cached
from llmsetup.runtimes.registry import register
from llmsetup.types import ModelSpec, RuntimeConfig
from llmsetup.util import http
from llmsetup.util.fs import app_dir, ensure_dir, write_text
from llmsetup.util.log import Console
from llmsetup.util.proc import first_line, format_command, run, spawn, which

DEFAULT_PORT = 11434


class OllamaRuntime(Runtime):
    name = "ollama"
    label = "Ollama"
    uses_gguf = True

    def __init__(self) -> None:
        self._applied_modelfiles: Dict[Tuple[int, str], str] = {}

    def is_available(self) -> bool:
        if which("ollama"):
            return True
        # A remote or containerised Ollama with no local CLI still counts.
        return http.request(f"http://127.0.0.1:{DEFAULT_PORT}/api/tags", timeout=2).ok

    def install_hint(self) -> str:
        return "install from https://ollama.com/download (or `brew install ollama`)"

    def version(self) -> Optional[str]:
        result = run(["ollama", "--version"], timeout=10)
        return first_line(result.output) if result.ok else None

    def derived_name(self, spec: ModelSpec) -> str:
        """Tag for our tuned variant. Kept distinct so we never shadow their model."""
        return f"llmsetup-{re.sub(r'[^a-z0-9._-]', '-', spec.id.lower())}"

    # ------------------------------------------------------------- modelfile

    def modelfile(self, spec: ModelSpec, config: RuntimeConfig) -> str:
        """Modelfile text carrying the tuning.

        ``num_gpu`` is Ollama's name for llama.cpp's ``-ngl``; ``num_ctx`` is the
        per-request context. Both are the tuner's output, expressed in Ollama's
        vocabulary.
        """
        base = spec.ollama_name if (spec.ollama_name and not config.extra.get("from_gguf")) \
            else config.model_path
        if base and base == config.model_path:
            source = Path(base)
            split = re.fullmatch(r"(.+)-00001-of-(\d{5})\.gguf", source.name)
            if split and int(split[2]) > 1:
                # Ollama uploads only files explicitly included by FROM. Merely
                # keeping sibling shards beside the first does not import them.
                base = str(source.with_name(f"{split[1]}-?????-of-{split[2]}.gguf"))
        lines = [
            "# Generated by llmsetup, tuned for this machine and use case.",
            f"FROM {base}",
            "",
            f"PARAMETER num_ctx {config.context_tokens}",
            f"PARAMETER num_gpu {config.llama_gpu_layers}",
            f"PARAMETER num_batch {config.ubatch_size}",
            f"PARAMETER temperature {config.temperature}",
            f"PARAMETER top_p {config.top_p}",
            f"PARAMETER top_k {config.top_k}",
            f"PARAMETER min_p {config.min_p}",
            f"PARAMETER repeat_penalty {config.repeat_penalty}",
        ]
        if config.threads:
            lines.append(f"PARAMETER num_thread {config.threads}")
        for stop in config.extra.get("stop", []):
            lines.append(f'PARAMETER stop "{stop}"')
        if config.extra.get("system_prompt"):
            lines += ["", f'SYSTEM """{config.extra["system_prompt"]}"""']
        return "\n".join(lines) + "\n"

    # ------------------------------------------------------------- lifecycle

    def ensure_model(self, spec: ModelSpec, config: RuntimeConfig,
                     console: Console) -> RuntimeConfig:
        # Resolve before starting a daemon or calling a fetching helper.
        cached = require_cached(spec, config.quant) if config.extra.get("cached_only") else None
        self._ensure_server(console, int(config.extra.get("ollama_port", DEFAULT_PORT)))

        # Native Ollama tags are mutable and cannot be pulled by digest. Import
        # the shared pinned GGUF instead, so a tag update cannot change a rerun.
        path = cached if cached is not None else fetch_gguf(spec, config.quant, console)
        config.model_path = str(path)
        config.extra["from_gguf"] = True
        console.warn(
            "Ollama copies GGUF weights into its own store, so this model "
            "will occupy disk twice (shared store + Ollama)"
        )

        self._create_model(spec, config, console)
        return config

    def _create_model(self, spec: ModelSpec, config: RuntimeConfig, console: Console) -> None:
        """Apply every Modelfile setting, including changes made by repair."""
        if config.extra.get("cached_only"):
            # A local FROM imports bytes; a tag FROM may implicitly pull them.
            config.model_path = str(require_cached(spec, config.quant))
            config.extra["from_gguf"] = True
        tag = self.derived_name(spec)
        port = int(config.extra.get("ollama_port", DEFAULT_PORT))
        contents = self.modelfile(spec, config)
        directory = ensure_dir(app_dir() / "modelfiles")
        path = write_text(directory / f"{tag}.Modelfile", contents)
        console.info(f"creating tuned model {tag} …")
        command = ["ollama", "create", tag, "-f", str(path)]
        result = run(command, timeout=3600, env={"OLLAMA_HOST": f"127.0.0.1:{port}"})
        if not result.ok:
            raise RuntimeUnavailable(
                f"`ollama create {tag}` failed: {result.failure(command)}",
                f"the Modelfile is at {path}",
            )
        config.served_name = tag
        self._applied_modelfiles[(port, tag)] = contents
        console.ok(f"tuned model available as `{tag}`")

    def start(self, spec: ModelSpec, config: RuntimeConfig, console: Console) -> Endpoint:
        endpoint_port = int(config.extra.get("ollama_port", DEFAULT_PORT))
        self._ensure_server(console, endpoint_port)
        model = self.launch_command(spec, config)[2]
        if (model == self.derived_name(spec) and
                self._applied_modelfiles.get((endpoint_port, model)) != self.modelfile(spec, config)):
            # Setting-only repairs reuse the weights and skip ensure_model.
            # Compare the entire Modelfile: context alone says nothing about
            # batch size, offload, threads, sampling, stops, or the system prompt.
            self._create_model(spec, config, console)
        return Endpoint(
            base_url=f"http://127.0.0.1:{endpoint_port}",
            model=model,
            runtime=self.name,
            supports_embeddings=spec.is_embedding,
            started_by_us=False,     # Ollama is a shared daemon; never kill it
        )

    def _ensure_server(self, console: Console, port: int = DEFAULT_PORT) -> None:
        if http.request(f"http://127.0.0.1:{port}/api/tags", timeout=2).ok:
            return
        if not which("ollama"):
            raise RuntimeUnavailable("Ollama is not installed", self.install_hint())
        if not http.port_is_free("127.0.0.1", port):
            raise RuntimeUnavailable(
                f"port {port} is in use by a service that is not a healthy Ollama server",
                f"stop the conflicting service; Rerun: {format_command(['ollama', 'serve'])}",
            )
        console.info("starting the Ollama server …")
        log = str(ensure_dir(app_dir() / "logs") / "ollama.log")
        command = ["ollama", "serve"]
        Path(log).write_text("", encoding="utf-8")
        process = spawn(command, log_path=log,
                        env={"OLLAMA_HOST": f"127.0.0.1:{port}"})
        endpoint = Endpoint(f"http://127.0.0.1:{port}", "", self.name,
                            started_by_us=True, log_path=log, process=process, command=command)

        def ready() -> bool:
            if process.poll() is not None:
                raise RuntimeUnavailable(f"Ollama exited with code {process.returncode}")
            return http.request(f"{endpoint.base_url}/api/tags", timeout=2).ok

        self.wait_until_ready(endpoint, ready, timeout=45, interval=1)

    def launch_command(self, spec: ModelSpec, config: RuntimeConfig) -> List[str]:
        # Only a successful create assigns the derived tag.
        # Older saved plans may still carry the catalog ID as served_name.
        if config.served_name == self.derived_name(spec):
            return ["ollama", "run", config.served_name]
        if config.extra.get("cached_only"):
            raise CachedModelUnavailable(
                f"--cached-only: tuned local model {spec.id}:{config.quant} has not been created"
            )
        if spec.ollama_name:
            return ["ollama", "run", spec.ollama_name]
        raise RuntimeUnavailable(
            "the tuned Ollama model has not been created and no official tag is known",
            "run `llmsetup setup` without `--dry-run` to create the tuned model",
        )

    def config_files(self, spec: ModelSpec, config: RuntimeConfig) -> Dict[str, str]:
        return {f"{self.derived_name(spec)}.Modelfile": self.modelfile(spec, config)}

    def local_model_path(self, spec: ModelSpec, config: RuntimeConfig) -> Optional[Path]:
        return Path(config.model_path) if config.model_path else None

    def env_overrides(self, config: RuntimeConfig) -> Dict[str, str]:
        """Server-level settings Ollama only reads from the environment.

        KV cache type and flash attention are daemon-wide in Ollama, not
        per-model, so these have to be set where the server starts, which is why
        the report prints them rather than silently applying them.
        """
        env = {}
        if config.kv_cache_type != "f16":
            env["OLLAMA_KV_CACHE_TYPE"] = config.kv_cache_type
            env["OLLAMA_FLASH_ATTENTION"] = "1"   # required for quantized KV
        elif config.flash_attention:
            env["OLLAMA_FLASH_ATTENTION"] = "1"
        if config.parallel > 1:
            env["OLLAMA_NUM_PARALLEL"] = str(config.parallel)
        return env


register(OllamaRuntime())
